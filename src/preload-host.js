// Ponte mínima entre a interface da central e o processo principal.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('central', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (parcial) => ipcRenderer.invoke('config:set', parcial),
  twitchLogado: () => ipcRenderer.invoke('twitch:logado'),
  salvarDebugLives: (dados) => ipcRenderer.invoke('debug:lives', dados),
  salvarDebugTelemetria: (dados) => ipcRenderer.invoke('debug:telemetria', dados),
  catalogo: () => ipcRenderer.invoke('catalogo:get'),
  especies: () => ipcRenderer.invoke('especies:get'),
  sprites: (ids) => ipcRenderer.invoke('sprites:pegar', ids),
  spriteNosso: (dex, shiny) => ipcRenderer.invoke('sprites:nosso', dex, shiny),
  salvarItensNossos: (lista) => ipcRenderer.invoke('catalogo:salvarNossos', lista),
  listarCredenciais: () => ipcRenderer.invoke('cred:listar'),
  salvarCredencial: (i, servico, usuario, senha) => ipcRenderer.invoke('cred:salvar', i, servico, usuario, senha),
  apagarCredencial: (i, servico) => ipcRenderer.invoke('cred:apagar', i, servico),
  preencherLogin: (idWebContents, i, servico) => ipcRenderer.invoke('cred:preencher', idWebContents, i, servico),
  entrarPeloNavegador: (i, servico) => ipcRenderer.invoke('navegador:entrar', i, servico),
  listarNavegadores: () => ipcRenderer.invoke('navegador:listar'),
  onSessaoNavegador: (cb) => ipcRenderer.on('navegador:sessao', (_e, dados) => cb(dados)),
  janela: (acao) => ipcRenderer.invoke('janela:acao', acao),
  instalarAtualizacao: () => ipcRenderer.invoke('atualizacao:instalar'),
  infoAtualizacao: () => ipcRenderer.invoke('atualizacao:info'),
  configNova: () => ipcRenderer.invoke('config:nova'),
  checarAtualizacao: () => ipcRenderer.invoke('atualizacao:checar'),
  onAtualizacao: (cb) => ipcRenderer.on('atualizacao', (_e, dados) => cb(dados)),
  limitesJanela: () => ipcRenderer.invoke('janela:limites'),
  redimensionarJanela: (b) => ipcRenderer.send('janela:redimensionar', b),
  onJanela: (cb) => ipcRenderer.on('janela:estado', (_e, dados) => cb(dados)),
  ligarPainelCelular: (ativo) => ipcRenderer.invoke('celular:ligar', ativo),
  novoCodigoCelular: () => ipcRenderer.invoke('celular:novoCodigo'),
  infoCelular: () => ipcRenderer.invoke('celular:info'),
  enviarSnapshotCelular: (dados) => ipcRenderer.send('celular:snapshot', dados),
  historicoCompras: () => ipcRenderer.invoke('historico:compras'),
  registrarCompras: (lista) => ipcRenderer.invoke('historico:registrarCompras', lista),
  historicoGlobal: () => ipcRenderer.invoke('historico:global'),
  registrarGlobal: (lista) => ipcRenderer.invoke('historico:registrarGlobal', lista)
});
